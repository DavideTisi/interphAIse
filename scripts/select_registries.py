#!/usr/bin/env python3
"""Choose physically distinct primary registries for one built contact by geometry alone.

In-plane offsets are fractions of the matched supercell. Shifting the coating by one of its own
surface-lattice vectors, or by a substrate surface-lattice vector (equivalently shifting the
substrate), leaves the structure unchanged. Offsets are therefore equivalent modulo the group H
generated by the rows of inv(T_film) and inv(T_substrate) (mod 1). The script reduces an n x n
grid to these translation classes, takes (0,0), then repeatedly adds the class farthest (minimum
Cartesian distance modulo H) from those already chosen, and finally checks with StructureMatcher
that no two chosen registries are symmetry-equivalent (rotation/mirror), replacing any that are.
No energies are evaluated.
"""
import argparse,copy,itertools,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
import numpy as np
from pymatgen.analysis.structure_matcher import StructureMatcher
from pymatgen.core.interface import Interface


def translation_group(t_film,t_sub,tol=1e-6):
    """Elements of H ⊂ (R/Z)^2 generated by the rows of inv(T_film) and inv(T_sub)."""
    gens=[np.mod(g,1) for g in np.vstack([np.linalg.inv(np.asarray(t_film,float)),np.linalg.inv(np.asarray(t_sub,float))])]
    key=lambda v:tuple(np.round(np.mod(v,1)%1,6))
    group={key(np.zeros(2)):np.zeros(2)};frontier=[np.zeros(2)]
    while frontier:
        nxt=[]
        for v in frontier:
            for g in gens:
                w=np.mod(v+g,1);k=key(w)
                if k not in group:group[k]=w;nxt.append(w)
        frontier=nxt
        if len(group)>10000:raise ValueError('translation group too large; check transformations')
    return np.array(list(group.values()))


def canonical(offset,group):
    return min(tuple(np.round(np.mod(offset+h,1)%1,6)) for h in group)


def distance(a,b,group,cell2d):
    d=np.inf
    for h in group:
        diff=np.mod(np.asarray(a)-np.asarray(b)+h+0.5,1)-0.5
        for shift in itertools.product((-1,0,1),repeat=2):
            d=min(d,float(np.linalg.norm((diff+shift)@cell2d)))
    return d


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('build',type=Path,help='build directory with interface.json and build.json')
    ap.add_argument('--grid',type=int,default=12);ap.add_argument('--count',type=int,default=3)
    ap.add_argument('--gap',type=float,default=2.0);ap.add_argument('--output',type=Path,required=True)
    args=ap.parse_args()
    build=json.loads((args.build/'build.json').read_text())
    iface=Interface.from_dict(json.loads((args.build/'interface.json').read_text()))
    group=translation_group(build['film_transformation'],build['substrate_transformation'])
    cell2d=iface.lattice.matrix[:2,:2]
    classes={}
    for i,j in itertools.product(range(args.grid),repeat=2):
        classes.setdefault(canonical(np.array([i,j])/args.grid,group),[]).append((i/args.grid,j/args.grid))
    reps={k:min(v) for k,v in classes.items()}   # grid representative: lexicographically smallest member
    chosen=[canonical(np.zeros(2),group)];rejected=[]
    # Tight tolerances: only exact symmetry equivalents (rotations/mirrors) count, not nearby registries.
    matcher=StructureMatcher(ltol=1e-3,stol=1e-2,angle_tol=0.1,primitive_cell=False,scale=False,attempt_supercell=False)
    def structure(offset):
        t=copy.deepcopy(iface);t.in_plane_offset=tuple(offset);t.gap=args.gap;return t
    while len(chosen)<min(args.count,len(reps)):
        remaining=[k for k in reps if k not in chosen and k not in rejected]
        if not remaining:break
        best=max(remaining,key=lambda k:(min(distance(reps[k],reps[c],group,cell2d) for c in chosen),[-x for x in reps[k]]))
        candidate=structure(reps[best])
        if any(matcher.fit(candidate,structure(reps[c])) for c in chosen):rejected.append(best);continue
        chosen.append(best)
    out={'build':str(args.build),'grid':args.grid,'gap_A':args.gap,'group_order':len(group),
         'n_translation_classes_on_grid':len(classes),
         'film_transformation':build['film_transformation'],'substrate_transformation':build['substrate_transformation'],
         'registries':[{'id':f'R{n+1}','offset':list(reps[k]),'class':list(k),
                        'min_distance_to_previous_A':None if n==0 else min(distance(reps[k],reps[c],group,cell2d) for c in chosen[:n])}
                       for n,k in enumerate(chosen)],
         'rejected_as_symmetry_equivalent':[list(reps[k]) for k in rejected],
         'rule':'(0,0) first; then farthest translation class (min Cartesian distance modulo H); not an exact symmetry equivalent (StructureMatcher ltol 1e-3, stol 1e-2, angle 0.1)'}
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(json.dumps(out,indent=1)+'\n')
    print(f"{args.build.name}: |H|={len(group)}, classes on {args.grid}x{args.grid} grid={len(classes)}, chosen="
          +', '.join(f"{r['offset']}" for r in out['registries'])+(f", rejected {out['rejected_as_symmetry_equivalent']}" if rejected else ''))

if __name__=='__main__':main()
